# Runtime image system packages. Debian packages come from snapshot.debian.org at the
# timestamp in apt-runtime-pins.txt, and PostgreSQL packages from the PGDG archive,
# which keeps every published version, so the exact pins stay installable.
#
#   sh deploy/apt-runtime.sh refresh YYYYMMDDTHHMMSSZ   rewrite the pins (host, needs Docker)
#   sh apt-runtime.sh install PINS                     install the pins (image build)
set -eu
fail() { printf '%s\n' "$*" >&2; exit 1; }
PGDG_KEY=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc
# Installed first, over plain HTTP: the slim base image has no CA certificates.
BOOTSTRAP='ca-certificates openssl libssl3'
# Everything else the runtime needs; apt adds their dependencies.
PACKAGES='postgresql-client-18'

debian_sources() {
  rm -f /etc/apt/sources.list /etc/apt/sources.list.d/debian.sources
  # Snapshot suites keep their original Valid-Until, so expired dates are expected.
  printf 'deb [check-valid-until=no] http://snapshot.debian.org/archive/%s/%s %s main\n' \
    debian "$1" bookworm debian "$1" bookworm-updates debian-security "$1" bookworm-security \
    > /etc/apt/sources.list.d/snapshot.list
}
pgdg_sources() {
  printf 'deb [signed-by=%s] https://%s/pub/repos/apt %s main\n' "$PGDG_KEY" "$1" "$2" > /etc/apt/sources.list.d/pgdg.list
}
update() { apt-get -qq -o Acquire::Retries=5 update; }
install() { apt-get -o Acquire::Retries=5 install --yes --no-install-recommends "$@"; }

case ${1:-} in
  install)
    pins=${2:?usage: apt-runtime.sh install PINS}
    stamp=$(sed -n 's/^# snapshot: //p' "$pins")
    [ -n "$stamp" ] || fail "$pins has no '# snapshot:' line"
    debian_sources "$stamp"
    update
    # Word splitting is intended: one package=version pin per word.
    # shellcheck disable=SC2046
    install $(for name in $BOOTSTRAP; do grep "^$name=" "$pins"; done)
    pgdg_sources apt-archive.postgresql.org bookworm-pgdg-archive
    update
    sed '/^#/d' "$pins" | xargs apt-get -o Acquire::Retries=5 install --yes --no-install-recommends
    rm -rf /var/lib/apt/lists/*
    ;;
  resolve)
    # Runs inside the Node base image; prints the new pins file.
    stamp=$2
    mkdir -p "$(dirname "$PGDG_KEY")" && cp /tmp/pgdg.asc "$PGDG_KEY"
    dpkg-query -W -f '${Package}=${Version}\n' | sort > /tmp/before
    debian_sources "$stamp"
    update >&2
    # Base image packages with newer versions in the snapshot are pinned as well.
    apt-get -o Acquire::Retries=5 upgrade --yes >&2
    # shellcheck disable=SC2086
    install $BOOTSTRAP >&2
    # The current stable PGDG release (the archive also holds pre-releases, so it can't choose).
    pgdg_sources apt.postgresql.org bookworm-pgdg
    update >&2
    # shellcheck disable=SC2086
    install $PACKAGES >&2
    dpkg-query -W -f '${Package}=${Version}\n' | sort | comm -13 /tmp/before - > /tmp/pins
    # The build installs from the archive, which can lag a new release by a day: prove every pin resolves there.
    pgdg_sources apt-archive.postgresql.org bookworm-pgdg-archive
    update >&2
    xargs apt-get install --simulate --yes --no-install-recommends < /tmp/pins > /dev/null \
      || fail 'The PGDG archive does not serve these versions yet; refresh again later.'
    printf '# SPDX-License-Identifier: AGPL-3.0-only\n# Generated by: sh deploy/apt-runtime.sh refresh %s\n# snapshot: %s\n' "$stamp" "$stamp"
    cat /tmp/pins
    ;;
  refresh)
    stamp=${2:-}
    printf '%s\n' "$stamp" | grep -Eq '^[0-9]{8}T[0-9]{6}Z$' || fail 'usage: sh deploy/apt-runtime.sh refresh YYYYMMDDTHHMMSSZ'
    here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
    image=$(sed -n 's/^ARG NODE_IMAGE=//p' "$here/Dockerfile")
    [ -n "$image" ] || fail 'NODE_IMAGE not found in deploy/Dockerfile'
    docker run --rm --network bridge \
      -v "$here/apt-runtime.sh:/tmp/apt-runtime.sh:ro" -v "$here/pgdg.asc:/tmp/pgdg.asc:ro" -e DEBIAN_FRONTEND=noninteractive \
      "$image" sh /tmp/apt-runtime.sh resolve "$stamp" > "$here/apt-runtime-pins.txt.new" \
      || { rm -f "$here/apt-runtime-pins.txt.new"; fail 'Refresh failed; the pins are unchanged.'; }
    mv "$here/apt-runtime-pins.txt.new" "$here/apt-runtime-pins.txt"
    ;;
  *) fail 'usage: sh deploy/apt-runtime.sh refresh YYYYMMDDTHHMMSSZ | install PINS' ;;
esac
