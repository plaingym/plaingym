test('parenthesized defaults keep their value and do not hide the next ALTER action', () => {
  assert.deepEqual(rollbackFindings("ALTER TABLE members ADD COLUMN safe text DEFAULT (concat('a', 'b')) NOT NULL, ADD COLUMN required text DEFAULT (NULL) NOT NULL, ALTER COLUMN required DROP NOT NULL;"), [
    { line: 1, rule: 'new NOT NULL column without a non-null DEFAULT: older inserts omit it' },
    { line: 1, rule: 'DROP NOT NULL: older readers may reject null stored values' },
  ]);
});

test('flags a dropped default, which older inserts of a NOT NULL column rely on', () => {
  assert.deepEqual(rollbackFindings('ALTER TABLE "members" ALTER COLUMN "status" DROP DEFAULT;'), [
    { line: 1, rule: 'DROP DEFAULT: older inserts that omit a NOT NULL column fail' },
  ]);
  assert.deepEqual(rollbackFindings(`ALTER TABLE members ALTER COLUMN status SET DEFAULT 'x';`), []);
});

for (const [alter, rule] of [
  ['ALTER COLUMN "Member Id" DROP IDENTITY IF EXISTS', 'DROP IDENTITY on "Member Id": older inserts that omit the column lose its generated value and fail'],
  ['ALTER member_id ADD GENERATED ALWAYS AS IDENTITY', 'ADD GENERATED AS IDENTITY on member_id: older inserts may fail on an explicit value or a conflicting sequence value'],
  ['ALTER member_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 10)', 'ADD GENERATED AS IDENTITY on member_id: older inserts may fail on an explicit value or a conflicting sequence value'],
  ['ALTER COLUMN member_id SET GENERATED ALWAYS', 'SET GENERATED ALWAYS on member_id: older inserts that supply a value are rejected'],
  ['ALTER COLUMN member_id RESTART WITH 10 SET GENERATED ALWAYS', 'SET GENERATED ALWAYS on member_id: older inserts that supply a value are rejected'],
  ['ALTER COLUMN member_id DROP EXPRESSION', 'DROP EXPRESSION on member_id: older inserts that omit the column lose its computed value'],
]) {
  test(`flags ${alter} on an existing column`, () => {
    const sql = `ALTER TABLE members ADD COLUMN optional text, ${alter};`;
    assert.deepEqual(rollbackFindings(sql), [{ line: 1, rule }]);
  });
}

test('flags a NULL default set on an existing column, which acts like a dropped default', () => {
  for (const sql of [
    'ALTER TABLE members ALTER COLUMN status SET DEFAULT NULL;',
    'ALTER TABLE members ALTER status SET DEFAULT (NULL::text);',
    'ALTER TABLE members ALTER COLUMN status SET DEFAULT CAST(NULL AS text);',
  ]) {
    assert.deepEqual(rollbackFindings(sql), [
      { line: 1, rule: 'SET DEFAULT NULL: older inserts that omit a NOT NULL column fail' },
    ], sql);
  }
  for (const sql of [
    "ALTER TABLE members ALTER COLUMN status SET DEFAULT (coalesce(NULL, 'x'));",
    'ALTER TABLE members ADD CONSTRAINT other_fk FOREIGN KEY (id) REFERENCES other(id) ON DELETE SET DEFAULT;',
    'ALTER TABLE members ADD CONSTRAINT other_fk FOREIGN KEY (gym_id, id) REFERENCES other(gym_id, id) ON DELETE SET DEFAULT (id);',
  ]) assert.deepEqual(rollbackFindings(sql), [], sql);
});

test('a column or constraint named type in a later action is not a type change', () => {
  for (const sql of [
    'ALTER TABLE members ADD COLUMN optional text, ADD type text;',
    'ALTER TABLE members ADD COLUMN optional text, DROP type;',
    'ALTER TABLE members ADD COLUMN optional text, ALTER CONSTRAINT type DEFERRABLE;',
  ]) assert.deepEqual(rollbackFindings(sql), [], sql);
  assert.deepEqual(rollbackFindings('ALTER TABLE members ADD COLUMN optional text, ALTER type TYPE bigint;'), [
    { line: 1, rule: 'SET DATA TYPE (or TYPE): older readers may reject new stored values' },
  ]);
});

test('refuses malformed quoted SQL instead of silently skipping the rest of a migration', () => {
  for (const sql of ["SELECT 'unfinished", 'SELECT "unfinished', 'SELECT $tag$unfinished', '/* unfinished', 'ALTER TABLE members ADD COLUMN required text DEFAULT (NULL NOT NULL;'])
    assert.throws(() => rollbackFindings(sql), /Unterminated SQL/);
  assert.throws(() => rollbackFindings('SELECT 1;\nALTER TABLE members ADD required text) NOT NULL;'),
    { message: 'Unmatched SQL parenthesis in the statement at line 2' });
});

test('checks only added SQL blobs between the supplied revisions, including the whole branch', () => {
  const cwd = mkdtempSync(join(tmpdir(), 'rollback-rules-'));
  const directory = 'packages/db/src/migrations';
  const run = (...args) => git(args, cwd);
  const write = (path, source) => writeFileSync(join(cwd, path), source);
  const commit = () => { run('add', '-A'); run('commit', '-m', 'feat: fixture migration'); return run('rev-parse', 'HEAD'); };
  try {
    run('init', '-b', 'main'); run('config', 'user.name', 'Release'); run('config', 'user.email', 'release@example.test');
    run('config', 'commit.gpgsign', 'false');
    mkdirSync(join(cwd, directory, 'meta'), { recursive: true });
    // The historical migration is deliberately unsafe: the lint never rechecks it.
    write(`${directory}/0000_old.sql`, 'ALTER TABLE members ADD COLUMN required text NOT NULL;');
    const base = commit();
    write(`${directory}/0001_safe.sql`, "ALTER TABLE members ADD COLUMN required text DEFAULT 'x' NOT NULL;");
    write(`${directory}/meta/0001_snapshot.json`, '{}');
    const safe = commit();
    assert.equal(checkRollback(base, safe, cwd), 1);
    write(`${directory}/0002_unsafe.sql`, '\nALTER TABLE members ADD COLUMN unsafe text NOT NULL;');
    const unsafe = commit();
    assert.throws(() => checkRollback(base, unsafe, cwd), /0002_unsafe.sql:2: new NOT NULL/);
    // A later push still checks an earlier migration on this branch.
    write('README.md', 'another commit\n'); commit();
    assert.throws(() => checkRollback(base, 'HEAD', cwd), /0002_unsafe.sql/);
    // Working files cannot hide a committed finding.
    write(`${directory}/0002_unsafe.sql`, 'SELECT 1;');
    assert.throws(() => checkRollback(base, unsafe, cwd), /0002_unsafe.sql/);
    write(`${directory}/0002_unsafe.sql`, 'ALTER TABLE members ADD CHECK (status IN (\'old\', \'new\'));');
    const check = commit();
    assert.throws(() => checkRollback(base, check, cwd), /changed CHECK/);
    write(`${directory}/0002_unsafe.sql`, '-- rollback-reviewed: major boundary; upgrade notes explain the new values\nALTER TABLE members ADD CHECK (true);');
    const reviewed = commit();
    assert.equal(checkRollback(base, reviewed, cwd), 2);
    // Edits to existing files belong to the separate append-only migration check.
    assert.equal(checkRollback(unsafe, reviewed, cwd), 0);
    // A migration the lint can't parse is named in the error.
    write(`${directory}/0003_malformed.sql`, 'ALTER TABLE members ADD required text) NOT NULL;');
    const malformed = commit();
    assert.throws(() => checkRollback(base, malformed, cwd), /0003_malformed\.sql: Unmatched SQL parenthesis/);
    assert.throws(() => checkRollback('', reviewed, cwd), /merge base/);
    assert.throws(() => checkRollback('0000000', reviewed, cwd), /merge base/);
  } finally { rmSync(cwd, { recursive: true, force: true }); }
});
